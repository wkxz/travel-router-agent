"""手工复现 EdgeOne CLI 的 agent-python 构建产物，用于本地跑起 /chat。

CLI 构建期做两件事：
  1. 把 agents/ 拷成 pages_agents/，并把 `from agents.X` 重写为 `from pages_agents.X`
  2. 递归生成 __init__.py
产物目录：.edgeone/agent-python/
  _platform/   ← 运行时模板（adapter/context/runtime/store/...）+ runtime_config.py
  pages_agents/← 重写后的业务代码
"""
import json
import os
import re
import shutil
import sys

ROOT = os.path.dirname(os.path.abspath(__file__))
TPL = r'C:/Users/K/.workbuddy-ai/binaries/node/workspace/node_modules/edgeone/edgeone-dist/pages/templates/agent-python'
OUT = os.path.join(ROOT, '.edgeone', 'agent-python')
PLAT = os.path.join(OUT, '_platform')
PKG = os.path.join(OUT, 'pages_agents')

if not os.path.exists(TPL):
    print(f"Error: Template directory not found: {TPL}", file=sys.stderr)
    sys.exit(1)

# 1. 拷贝 _platform 运行时模板
os.makedirs(PLAT, exist_ok=True)
for f in ('adapter.py', 'context.py', 'runtime.py', 'store.py', 'memory.py',
          'local_blob_store.py', 'mcp_handler.py', '__init__.py'):
    src_f = os.path.join(TPL, f)
    if os.path.exists(src_f):
        shutil.copy(src_f, os.path.join(PLAT, f))
        print('platform:', f)

# 2. 生成 runtime_config.py（CLI 生成的内容）
with open(os.path.join(PLAT, 'runtime_config.py'), 'w', encoding='utf-8') as fh:
    fh.write('\n'.join([
        '# Generated by EdgeOne CLI. Do not edit manually.',
        'AGENT_MODE = "dev"',
        'AGENT_FRAMEWORK = "openai-agents-sdk"',
        'SANDBOX_TIMEOUT = None',
        'SANDBOX_API_ENV = "production"',
        'BUILDER_PROJECT_ID = ""',
        '',
    ]))
print('platform: runtime_config.py (dev mode)')

# 3. 拷贝并重写 agents/ -> pages_agents/
agents_dir = os.path.join(ROOT, 'agents')
if not os.path.exists(agents_dir):
    print(f"agents directory does not exist yet at {agents_dir}, skipping rewrite.")
    sys.exit(0)

if os.path.exists(PKG):
    shutil.rmtree(PKG)
shutil.copytree(agents_dir, PKG)

# 只重写 "from agents.<本地模块>"，不要动 "from agents import Agent" 这类 SDK 符号导入
REWRITE = re.compile(r'\bfrom\s+agents\.')
changed = 0
for dirpath, _dirs, files in os.walk(PKG):
    # 递归补 __init__.py
    init = os.path.join(dirpath, '__init__.py')
    if not os.path.exists(init):
        open(init, 'w').close()
    for fn in files:
        if not fn.endswith('.py') or fn == '__init__.py':
            continue
        p = os.path.join(dirpath, fn)
        src = open(p, encoding='utf-8').read()
        new = REWRITE.sub('from pages_agents.', src)
        if new != src:
            open(p, 'w', encoding='utf-8').write(new)
            changed += 1
print(f'pages_agents: rewritten {changed} file(s)')

# 4. 打印建议的路由表（注意：精确路径，不要写正则 ^...$）
routes = {
    "/chat": {"module": "pages_agents.chat.index", "isIndex": True},
    "/chat/stop": {"module": "pages_agents.chat.stop", "isIndex": False}
}
print('\nAGENT_ROUTE_TABLE=' + json.dumps(routes, ensure_ascii=False))
